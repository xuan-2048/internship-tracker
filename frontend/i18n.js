let language = 'en';
try { if (localStorage.getItem('tracker-language') === 'zh') language = 'zh'; } catch { /* Storage may be unavailable. */ }

function t(key, values = {}) {
  const template = messages[key][language === 'zh' ? 1 : 0];
  return template.replace(/\{(\w+)\}/g, (match, name) => values[name] ?? match);
}

function translatedError(message) {
  const match = Object.keys(messages).find(key => messages[key][0] === message);
  if (match) return t(match);
  const field = /^The (\w+) field must be text within the allowed length\.$/.exec(message);
  return field ? t('invalidField', {field: field[1]}) : t('genericError');
}
